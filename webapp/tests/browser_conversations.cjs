const assert = require('node:assert/strict');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  const browser = await chromium.launch({headless:true,channel:process.env.PLAYWRIGHT_CHANNEL || 'chrome'});
  try {
    const page = await browser.newPage({viewport:{width:1536,height:1024}}), errors = [];
    await page.clock.install({time:new Date('2026-10-15T04:00:00Z')});
    page.on('pageerror',e => errors.push(e.message));
    await page.goto(process.env.LABLOG_TEST_URL || 'http://127.0.0.1:8016');
    await page.waitForSelector('.conversation-row');
    assert.equal(await page.locator('.conversation-row').count(),2);
    assert.equal(await page.locator('#count-all').innerText(),'2');
    assert.equal(await page.locator('#count-workbuddy').innerText(),'1');
    await page.locator('[data-source="workbuddy"]').click();
    await page.waitForFunction(() => document.querySelectorAll('.conversation-row').length === 1);
    await page.locator('.conversation-title').click();
    await page.waitForFunction(() => document.querySelector('#evidence-caption').textContent.includes('原始消息') && document.querySelectorAll('.message-text').length === 50);
    assert.ok((await page.locator('#task-info').innerText()).includes('WorkBuddy · 布局与异常恢复'));
    assert.ok((await page.locator('#evidence-content').innerText()).includes('工作待验证'));
    await page.locator('#messages-next').click();
    await page.waitForFunction(() => document.querySelectorAll('.message-text').length === 6);
    await page.getByRole('tab',{name:'执行记录',exact:true}).click();
    await page.waitForFunction(() => document.querySelectorAll('.message-text').length === 2);
    assert.ok((await page.locator('#evidence-content').innerText()).includes('run_tests'));
    assert.ok(!(await page.locator('#evidence-content').innerText()).includes('do not display'));
    const checkbox = page.locator('.conversation-row input');
    assert.equal(await checkbox.isChecked(),false);
    await checkbox.check();
    await page.waitForFunction(() => document.querySelector('#selected-count').textContent === '1');
    await page.reload();
    await page.waitForSelector('.conversation-row');
    // A fresh browser state restores the project and durable selection.
    assert.equal(await page.locator('.conversation-row[data-key="workbuddy:wb-main"] input').isChecked(),true);
    await page.locator('[data-source="workbuddy"]').click();
    await page.waitForFunction(() => document.querySelectorAll('.conversation-row').length === 1);
    await page.getByRole('tab',{name:'任务摘要',exact:true}).click();
    assert.ok((await page.locator('#evidence-content').innerText()).includes('消息数：56'));
    await page.locator('textarea[data-field="completed"]').fill('人工保存的工作正文。');
    await page.locator('#save-btn').click();
    await page.waitForFunction(() => document.querySelector('#save-state').textContent.startsWith('已保存'));
    await page.locator('.conversation-row input').uncheck();
    await page.waitForFunction(() => document.querySelector('#selected-count').textContent === '0');
    assert.equal(await page.locator('textarea[data-field="completed"]').inputValue(),'人工保存的工作正文。');
    await page.locator('[data-source="all"]').click();
    await page.waitForFunction(() => document.querySelectorAll('.conversation-row').length === 2);
    await page.locator('#status-filter').selectOption('archived');
    await page.waitForFunction(() => document.querySelectorAll('.conversation-row').length === 3);
    await page.locator('#task-search').fill('WorkBuddy');
    await page.waitForFunction(() => document.querySelectorAll('.conversation-row').length === 1);
    await page.locator('#task-search').fill('');
    await page.locator('#status-filter').selectOption('');
    await page.waitForFunction(() => document.querySelectorAll('.conversation-row').length === 2);
    const projectBeforeFailure = await page.locator('#project-filter').inputValue();
    const vrProject = await page.locator('#project-filter option').evaluateAll(options => options.find(o => o.textContent.startsWith('VR ')).value);
    await page.route('**/api/v1/workspace/conversations?*',route => route.abort('failed'));
    await page.locator('#project-filter').selectOption(vrProject);
    await page.waitForFunction(() => document.querySelector('#task-tree').textContent.includes('会话列表加载失败'));
    assert.equal(await page.locator('.conversation-row').count(),0);
    await page.unroute('**/api/v1/workspace/conversations?*');
    await page.locator('#project-filter').selectOption(projectBeforeFailure);
    await page.waitForFunction(() => document.querySelectorAll('.conversation-row').length === 2);
    await page.getByRole('tab',{name:'原始对话',exact:true}).click();
    await page.locator('.conversation-row[data-key="workbuddy:wb-main"] .conversation-title').click();
    await page.waitForSelector('.message-text');
    await page.locator('#toast').waitFor({state:'hidden'});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth),false);
    await page.screenshot({path:'.tmp/workbuddy-conversations-desktop.png',fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth),false);
    await page.locator('#open-tasks').click();
    assert.ok(await page.locator('#tasks-panel.open').isVisible());
    await page.screenshot({path:'.tmp/workbuddy-conversations-mobile.png',fullPage:true});
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({passed:true,pageErrors:errors,checks:['project titles','source counts','56-message paging','real tools','persistent selection','manual draft retained','archived filter','title search','failed project switch','desktop/mobile layout']}));
  } finally {await browser.close();}
})().catch(e => {console.error(e);process.exitCode=1;});
